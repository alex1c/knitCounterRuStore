/** Stable ordered list of section ids (for tests and search helpers). */
export const GUIDE_SECTION_IDS: GuideSectionId[] = GUIDE_SECTIONS.map(
	(section) => section.id
)

/** Look up a guide section by stable id. */
export function getGuideSection(
	id: string
): GuideSection | undefined {
	return GUIDE_SECTIONS.find((section) => section.id === id)
}
